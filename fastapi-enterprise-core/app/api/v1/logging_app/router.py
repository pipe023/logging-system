# --- VALIDATION DEPENDENCY (Used for /ingest) ---
def verify_token(x_api_key: str = Header(...), db: Session = Depends(get_db)):
  key_hash = hashlib.sha256(x_api_key.encode()).hexdigest()
  user = (
      db.query(User)
      .filter(
          User.api_key_hash == key_hash,
          User.is_active == True,
          User.is_deleted == False,
      )
      .first()
  )

  if not user:
    raise HTTPException(status_code=403, detail="Invalid API Key")
  return user


