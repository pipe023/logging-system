@router.post("/generate-report")
async def generate_log_pdf_report(payload: ReportRequest):
  """Generates an A4 PDF report with direct error exposure and safe stream response."""
  if not payload.logs:
    raise HTTPException(
        status_code=400, detail="No log entries provided for reporting."
    )

  try:
    pdf_bytes = generate_pdf_report(payload.logs, payload.model)
    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": (
                "attachment; filename=system_log_report.pdf"
            )
        },
    )
  except Exception as e:
    err_detail = traceback.format_exc()
    print("\n========== CRASH TRACEBACK ==========")
    print(err_detail)
    print("=====================================\n")
    raise HTTPException(
        status_code=500,
        detail=str(e) + " | Check server console for full traceback.",
    )