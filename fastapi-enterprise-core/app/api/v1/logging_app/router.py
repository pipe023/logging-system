async def get_log_users(db: Session = Depends(get_db)):
  results = db.query(LogEntry.user_id).distinct().all()
  user_ids = [r[0] for r in results if r[0]]

  if not user_ids:
    return []

  users = db.query(User).filter(User.id.in_(user_ids)).all()

  return [
      {"user_id": str(u.id), "username": getattr(u, "username", u.email)}
      for u in users
  ]


