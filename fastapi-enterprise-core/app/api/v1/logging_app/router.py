@router.get("/analytics/summary")
@router.get("/summary")
async def get_log_summary(db: Session = Depends(get_db)):
  level_counts = (
      db.query(LogEntry.level, func.count(LogEntry.id))
      .group_by(LogEntry.level)
      .all()
  )
  service_counts = (
      db.query(LogEntry.service_name, func.count(LogEntry.id))
      .group_by(LogEntry.service_name)
      .all()
  )
  total_logs = db.query(LogEntry).count()

  return {
      "total_logs": total_logs,
      "level_distribution": dict(level_counts),
      "service_distribution": dict(service_counts),
  }


