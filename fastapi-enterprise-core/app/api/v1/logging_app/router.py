@router.post("/ingest", response_model=LogsResponse)
async def ingest_log(
    log_in: LogsCreate,
    db: Session = Depends(get_db),
    current_user: User = Depends(verify_token),
):
  log_data = log_in.model_dump()

  if "extra" in log_data and log_data["extra"] is not None:
    log_data["extra_attributes"] = log_data.pop("extra")

  if not log_data.get("user_id"):
    message = log_data.get("message", "")
    match = re.search(r"User '([^']+)'", message)

    if match:
      target_username = match.group(1)
      found_user = (
          db.query(User).filter(User.username == target_username).first()
      )

      if found_user:
        log_data["user_id"] = str(found_user.id)
      else:
        try:
          dummy_password_hash = pwd_context.hash("autogenerated-calculator-user")
          new_auto_user = User(
              email=f"{target_username}@calculator.local",
              username=target_username,
              hashed_password=dummy_password_hash,
              is_active=True,
              is_deleted=False,
          )
          db.add(new_auto_user)
          db.commit()
          db.refresh(new_auto_user)
          log_data["user_id"] = str(new_auto_user.id)
        except Exception as e:
          db.rollback()
          print(f"Error auto-creating user from log: {e}")
          log_data["user_id"] = None
    else:
      if getattr(current_user, "username", None) == "todo-application":
        log_data["user_id"] = None
      else:
        log_data["user_id"] = str(current_user.id)

  new_log = LogEntry(**log_data)
  db.add(new_log)
  db.commit()
  db.refresh(new_log)
  return new_log


